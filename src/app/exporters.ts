import { specView } from "../shared/agentView";
import type { FormInfo, InjectedToolDef, InspectedTool } from "../shared/types";
import type { SavedOverride } from "./storage";

const attr = (value: string) => value.replace(/&/g, "&amp;").replace(/"/g, "&quot;");

/** The markup a site owner adds to a form to ship what was prototyped in the inspector. */
export function formHtmlSnippet(form: FormInfo): string {
  const formAttrs = [
    form.toolname && `toolname="${attr(form.toolname)}"`,
    form.tooldescription && `tooldescription="${attr(form.tooldescription)}"`,
    form.toolautosubmit && "toolautosubmit",
  ].filter(Boolean);
  const lines = [`<form ${formAttrs.join(" ")}${form.action ? ` action="${attr(form.action)}"` : ""} method="${form.method.toLowerCase()}">`];
  for (const field of form.fields) {
    if (!field.name) continue;
    const tag = field.tag === "select" || field.tag === "textarea" ? field.tag : "input";
    const typeAttr = tag === "input" ? ` type="${field.type}"` : "";
    const desc = field.toolparamdescription ? ` toolparamdescription="${attr(field.toolparamdescription)}"` : "";
    const close = tag === "input" ? ">" : `>…</${tag}>`;
    lines.push(`  <${tag}${typeAttr} name="${attr(field.name)}"${desc}${field.required ? " required" : ""}${close}`);
  }
  lines.push("  …", "</form>");
  return lines.join("\n");
}

/** An imperative equivalent of any tool, with feature detection for browsers that only have the old name. */
export function registerToolSnippet(tool: InspectedTool, code?: string): string {
  const fields = JSON.stringify(specView(tool), null, 2).split("\n").slice(1, -1).join("\n");
  const execute =
    code ??
    (tool.source === "declarative"
      ? "// Fill and submit the form, or call your API directly, and return what the agent needs.\nreturn { ok: true };"
      : "// Do the work and return a string or a JSON-serializable value.\nreturn { ok: true };");
  return [
    "const modelContext = document.modelContext ?? navigator.modelContext;",
    "const controller = new AbortController();",
    "",
    "modelContext?.registerTool({",
    `${fields},`,
    "  async execute(input, { signal } = {}) {",
    execute.replace(/^/gm, "    "),
    "  },",
    "}, { signal: controller.signal });",
    "",
    "// controller.abort() removes the tool again.",
  ].join("\n");
}

/** Mirrors formKey() in src/extension/forms.ts so the generated extension finds the same forms. */
const FIND_FORM_SOURCE = `function formKey(form, forms) {
  if (form.id) return '#' + form.id;
  var name = form.getAttribute('name');
  if (name) return 'form[name="' + name + '"]';
  var toolname = form.getAttribute('toolname');
  if (toolname && !form.hasAttribute('data-webmcp-inspector')) return 'form[toolname="' + toolname + '"]';
  var action = form.getAttribute('action') || '';
  var siblings = forms.filter(function (f) { return (f.getAttribute('action') || '') === action && !f.id && !f.getAttribute('name'); });
  return 'form[action="' + action + '"]:' + siblings.indexOf(form);
}
function findForm(key) {
  var forms = Array.prototype.slice.call(document.querySelectorAll('form'));
  return forms.find(function (f) { return formKey(f, forms) === key; }) || null;
}`;

/**
 * A standalone Webfuse extension that applies the augmentations and script tools to every visitor
 * of a Space, so what was prototyped here can ship without touching the site.
 */
export function webfuseExtension(pageUrl: string, overrides: SavedOverride[], tools: InjectedToolDef[]) {
  const url = new URL(pageUrl);
  const content = `// Generated by WebMCP Inspector for ${url.origin}${url.pathname}
(function () {
  if (location.pathname.replace(/\\/+$/, '') !== ${JSON.stringify(url.pathname.replace(/\/+$/, ""))}) return;
  var OVERRIDES = ${JSON.stringify(overrides.map(({ formKey, form, fields }) => ({ formKey, form, fields })), null, 2)};
  ${FIND_FORM_SOURCE.replace(/\n/g, "\n  ")}
  function applyOverrides() {
    OVERRIDES.forEach(function (o) {
      var form = findForm(o.formKey);
      if (!form) return;
      Object.keys(o.form).forEach(function (name) {
        var value = o.form[name];
        if (value === null || value === 'false') form.removeAttribute(name);
        else form.setAttribute(name, name === 'toolautosubmit' ? '' : value);
      });
      Object.keys(o.fields).forEach(function (key) {
        var field = form.querySelector('[name="' + key + '"]') || document.getElementById(key);
        var desc = o.fields[key].toolparamdescription;
        if (field && desc) field.setAttribute('toolparamdescription', desc);
      });
    });
  }
  applyOverrides();
  new MutationObserver(applyOverrides).observe(document.documentElement, { childList: true, subtree: true });

  var modelContext = document.modelContext || navigator.modelContext;
  if (!modelContext) return;
${tools
  .map(
    (t) => `  modelContext.registerTool(Object.assign(${JSON.stringify(
      { name: t.name, title: t.title || undefined, description: t.description, inputSchema: t.inputSchema, outputSchema: t.outputSchema, annotations: t.annotations },
      null,
      2,
    ).replace(/\n/g, "\n  ")}, {
    execute: async function (input, options) {
${t.code.replace(/^/gm, "      ")}
    }
  }));`,
  )
  .join("\n")}
})();
`;
  const manifest = {
    manifest_version: 3,
    name: `WebMCP tools for ${url.hostname}`,
    version: "1.0.0",
    description: "Adds WebMCP tools to the page. Generated by WebMCP Inspector.",
    content_scripts: [{ matches: [`${url.origin}/*`], js: ["content.js"], run_at: "document_idle" }],
  };
  return { content, manifest: JSON.stringify(manifest, null, 2) };
}
